"""
Turning two numbers into one, and one number into something a person can read.
← YOU BUILD THIS IN MILESTONES 4 AND 5

The combining rule, label mapping, and reader-facing messages are implemented.

`combine_signals` is where your false-positive decision from Milestone 1
actually gets made. Everything above it — the labels, the appeal path — is
downstream of a number this function produced.

`score_to_label` returns a machine-readable label and the combined score as
confidence. Higher confidence values mean the text scores as more AI-like.

⚠️ Your README's **Signals and Scoring** section has to name the file and
function holding your combining rule. The grader checks your code against what
you claim, so that line should read `scoring.py::combine_signals`.
"""

import config


LABEL_TEXT = {
    "human": (
        "Our checks suggest this text was written by a person. "
        "This assessment can be wrong."
    ),
    "unsure": (
        "We do not have enough evidence to determine how this text was written. "
        "The writer can request a review."
    ),
    "ai": (
        "Our checks suggest this text may have been generated by AI. "
        "This assessment can be wrong, and the writer can request a review."
    ),
}


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine signals with 70% model weight and 30% style weight.

    Both inputs point the same way: higher means more AI-like.
    Weights are named constants in config.py and sum to 1.0.

    Args:
        model_score: from `detector.model_signal` — how predictable the text is.
        style_score: from `stylometry.style_signal` — the shape of the text.

    Returns:
        A float in [0, 1] for inputs in [0, 1]:
        0.7 * model_score + 0.3 * style_score.
        This is a heuristic score, not a calibrated probability.
    """
    return (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    )


def combine_appeal_signals(model_score: float, style_score: float) -> float:
    """Combine an appeal variant's signals with 60% model and 40% style."""
    return (
        config.APPEAL_WEIGHT_MODEL_SIGNAL * model_score
        + config.APPEAL_WEIGHT_STYLE_SIGNAL * style_score
    )


def score_to_label(score: float) -> tuple[str, float]:
    """
    Turn a combined score in [0, 1] into (label, confidence).

    Returns:
        A label of "ai" at or above config.AI_THRESHOLD, "human" at or
        below config.HUMAN_THRESHOLD, or "unsure" between those thresholds.
        Confidence is the input score as a float: higher means more AI-like,
        not greater certainty in the selected label or a calibrated probability.
        LABEL_TEXT maps the returned label to the sentence shown to the reader.
    """
    confidence = float(score)
    if score >= config.AI_THRESHOLD:
        return "ai", confidence
    if score <= config.HUMAN_THRESHOLD:
        return "human", confidence
    return "unsure", confidence


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 <= score <= {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} < score < {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} <= score <= 1.00"),
    ]
